import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { chromium, expect } from '@playwright/test';
import { launchFixture } from './support.mjs';

test('Library selective parity: isolated real assets, addressable workspace, and safe authoring', { timeout: 240000 }, async t => {
  const server = await launchFixture({ proposals: true });
  t.after(() => server.stop());
  assert.ok(server.documentPath.startsWith(`${server.root}${path.sep}`));
  const fixtureContent = `${server.content}\nThis checklist covers a clean recovery onto a replacement laptop. Keep the original disk untouched until the restored system has been verified.\n\n## Before you begin\n\n- Confirm that the backup belongs to the right machine.\n- Check the backup date and available disk space.\n- Have the recovery key ready before you start.\n\n## Verification\n\nKeep a checksum. Restore a small sample first, then confirm that the files open correctly before starting the full recovery.\n\n## Escalation\n\nIf verification fails, stop the recovery and record which check failed. Read [[shared//knowledge/shared-backup|shared guidance]] before trying another backup.\n`;
  await writeFile(server.documentPath, fixtureContent);
  await mkdir(path.join(server.root, 'personal/knowledge/recovery/nested'), { recursive: true });
  execFileSync(process.execPath, [server.launcher, 'index', '--full', '--format', 'json', '-q'], { env: server.env, timeout: 60000, stdio: 'pipe' });
  const browser = await chromium.launch({ headless: true }); t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const failures = []; page.on('pageerror', e => failures.push(e.stack ?? e.message));
  await page.goto(server.url + '#/search');
  const hash = async value => { await page.evaluate(value => { location.hash = value; }, value); };
  const workspace = page.getByRole('region', { name: 'Asset workspace', exact: true });
  const screenshotRoot = process.env.AKM_DESKTOP_SCREENSHOTS;
  const screenshot = async name => { if (screenshotRoot) { await mkdir(screenshotRoot, { recursive: true }); await page.evaluate(() => scrollTo(0, 0)); await workspace.evaluate(el => el.scrollTo(0, 0)); await page.screenshot({ path: path.join(screenshotRoot, name), fullPage: true, animations: 'disabled' }); } };

  await t.test('actual command/agent/document bodies load in deep-linked rendered and source views', async () => {
    for (const [ref, body] of [['personal//commands/check-recovery', 'Review the recovery evidence'], ['personal//agents/recovery-reviewer', 'Explain which recovery checks'], [server.refs.document, 'Verify the checksum']]) {
      await hash(`#/asset?ref=${encodeURIComponent(ref)}`);
      await expect(workspace.locator('.document-body')).toContainText(body);
      await workspace.getByRole('button', { name: 'More', exact: true }).click();
      await workspace.getByRole('button', { name: 'Source', exact: true }).click();
      await expect(workspace.locator('.raw-source')).toContainText(body);
      await workspace.getByRole('button', { name: 'Read', exact: true }).click();
    }
    await expect(workspace.getByRole('heading', { name: 'Restore a laptop', exact: true })).toHaveCount(1);
    await expect(workspace.getByRole('link', { name: 'View in folder', exact: true })).toBeVisible();
    if (!await workspace.locator('.heading-navigation').evaluate(element => element.open)) await workspace.getByText('On this page', { exact: true }).click();
    await workspace.getByRole('link', { name: 'Escalation', exact: true }).click();
    await expect(workspace.locator('#h-escalation')).toBeVisible();
    await expect(page).toHaveURL(/section=escalation/);
    await workspace.getByRole('link', { name: 'shared guidance', exact: false }).click();
    await expect(workspace.locator('.document-body')).toContainText('Keep the original disk.');
    await page.goBack();
    await expect(workspace.locator('.document-body')).toContainText('Keep a checksum.');
    await page.setViewportSize({ width: 1280, height: 860 });
    await screenshot('parity-asset-desktop.png');
    await workspace.getByRole('link', { name: 'Edit page', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Markdown source, including optional frontmatter' })).toHaveValue(fixtureContent);
    assert.ok(await page.locator('.source-editor').evaluate(el => el.getBoundingClientRect().width > 300 && el.getBoundingClientRect().width <= parseFloat(getComputedStyle(el).maxInlineSize) + 1), 'Source editing keeps a readable maximum measure while using the available pane');
    await screenshot('library-edit-desktop.png');
    await workspace.getByRole('link', { name: 'Back to file', exact: true }).click();
    await expect(workspace.locator('.document-body')).toContainText('Keep a checksum.');
  });
  await t.test('scoped search and active scope filters preserve URL/return context', async () => {
    await hash('#/search?tab=browse&bundle=personal&limit=100');
    await expect(page.locator('.library-hit-content').first()).toBeVisible();
    await page.getByRole('region', { name: 'Search results' }).getByRole('link').filter({ hasText: 'restore laptop' }).click();
    await expect(workspace.locator('.document-body')).toContainText('Verify the checksum');
    await page.goBack();
    await expect(page).toHaveURL(/bundle=personal/);
    await expect(page).toHaveURL(/limit=100/);
    if (!await page.locator('.search-filters').evaluate(el => el.open)) await page.locator('.search-filters summary').click();
    await page.getByRole('textbox', { name: 'Scope: user', exact: true }).fill('synthetic-reader');
    await page.getByRole('button', { name: 'Apply filters', exact: true }).click();
    await expect(page).toHaveURL(/scope_user=synthetic-reader/);
    await expect(page.locator('.search-filters summary')).toContainText('Filters (3)');
    await page.locator('.search-filters > summary').click();
    await expect(page.getByRole('textbox', { name: 'Scope: user', exact: true })).toHaveValue('synthetic-reader');
    await page.keyboard.press('Escape');
    await expect(page.locator('.search-filters > summary')).toBeFocused();
    await hash('#/search?bundle=personal&q=backup');
    await expect(page.locator('.search-filters > summary')).toHaveText('Filters (1)');
    await page.locator('.search-filters > summary').click();
    await page.locator('.search-filters').getByRole('combobox', { name: 'Bundle', exact: true }).selectOption('vendor');
    await page.keyboard.press('Escape');
    await expect(page.locator('.search-filters > summary')).toHaveText('Filters (1)');
    await page.locator('.search-filters > summary').click();
    await expect(page.locator('.search-filters').getByRole('combobox', { name: 'Bundle', exact: true })).toHaveValue('personal');
    await page.locator('.search-filters').getByRole('button', { name: 'Cancel', exact: true }).click();
  });
  await t.test('an older in-flight read cannot replace a newer selected asset', async () => {
    const documentResponse = (await server.call(`/api/asset?ref=${encodeURIComponent(server.refs.document)}`)).body;
    await page.route('**/api/asset?*', async route => {
      if (new URL(route.request().url()).searchParams.get('ref') !== server.refs.document) return route.continue();
      await new Promise(resolve => setTimeout(resolve, 200));
      await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(documentResponse) }).catch(() => {});
    });
    const requested = page.waitForRequest(r => r.url().includes('/api/asset?') && new URL(r.url()).searchParams.get('ref') === server.refs.document);
    await hash(`#/asset?ref=${encodeURIComponent(server.refs.document)}`); await requested;
    await hash('#/asset?ref=personal%2F%2Fagents%2Frecovery-reviewer');
    await expect(workspace.locator('.document-body')).toContainText('Explain which recovery checks');
    await page.waitForTimeout(250);
    await expect(workspace.locator('.document-body')).toContainText('Explain which recovery checks');
    await page.unroute('**/api/asset?*');
  });
  await t.test('scoped folder picker, default target, creation preview, and keyboard tabs work', async () => {
    await hash('#/new?returnTo=%23%2Fsearch%3Fbundle%3Dpersonal');
    await expect(workspace.getByRole('combobox', { name: 'Bundle', exact: true })).toHaveValue('personal');
    await page.getByRole('textbox', { name: 'File name', exact: true }).fill('parity-created');
    await page.getByRole('button', { name: 'Browse…', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await expect(dialog.getByRole('button', { name: 'Up', exact: true })).toBeDisabled();
    await dialog.getByRole('button', { name: /recovery/ }).click();
    await dialog.getByRole('button', { name: 'Use this folder', exact: true }).click();
    await expect(page.getByRole('textbox', { name: 'Folder under knowledge/', exact: false })).toHaveValue('recovery');
    const editor = page.getByRole('textbox', { name: 'Markdown source, including optional frontmatter', exact: true });
    await editor.fill('# Parity created\n\nA retained synthetic draft.\n');
    await page.getByRole('tab', { name: 'Markdown', exact: true }).focus();
    await page.keyboard.press('ArrowRight');
    await expect(page.getByRole('tab', { name: 'Preview', exact: true })).toHaveAttribute('aria-selected', 'true');
    await expect(page.locator('#editor-preview')).toContainText('A retained synthetic draft.');
    await screenshot('parity-create-preview.png');
    await page.getByRole('tab', { name: 'Preview', exact: true }).press('ArrowLeft');
    const response = page.waitForResponse(r => r.url().endsWith('/api/knowledge/create') && r.status() === 200);
    await page.getByRole('button', { name: 'Create knowledge', exact: true }).click(); await response;
    await expect(workspace.locator('.document-body')).toContainText('A retained synthetic draft.');
    assert.match(await readFile(path.join(server.root, 'personal/knowledge/recovery/parity-created.md'), 'utf8'), /retained synthetic draft/);
  });
  await t.test('feedback tags and exact-text fixes preserve existing API payloads', async () => {
    await hash(`#/asset?ref=${encodeURIComponent(server.refs.document)}`);
    await expect(workspace.locator('.document-body')).toContainText('Keep a checksum.');
    await workspace.getByRole('button', { name: 'Add feedback', exact: true }).click();
    await expect(workspace.getByRole('region', { name: 'Feedback', exact: true })).toBeVisible();
    await workspace.getByRole('textbox', { name: 'Tags (optional)', exact: true }).fill('team:synthetic, topic:recovery');
    const feedback = page.waitForRequest(r => r.url().endsWith('/api/feedback') && r.method() === 'POST');
    await workspace.getByRole('button', { name: 'Record feedback', exact: true }).click();
    assert.deepEqual((await feedback).postDataJSON().tags, ['team:synthetic', 'topic:recovery']);
    await expect(workspace.getByRole('status')).toContainText('Feedback recorded');
    await workspace.getByRole('button', { name: 'Read', exact: true }).click();
    await workspace.getByRole('button', { name: 'Suggest a correction', exact: true }).click();
    await expect(workspace.getByRole('heading', { name: 'Suggest a fix', exact: true })).toBeVisible();
    await workspace.getByRole('textbox', { name: 'Replace this exact text', exact: true }).fill('Keep a checksum.');
    await workspace.getByRole('textbox', { name: 'With', exact: true }).fill('Keep a verified checksum.');
    await workspace.getByRole('textbox', { name: 'Why', exact: true }).fill('Synthetic evidence-backed clarification.');
    await workspace.getByRole('textbox', { name: 'Source (optional)', exact: true }).fill('Synthetic fixture checklist');
    const fix = page.waitForRequest(r => r.url().endsWith('/api/feedback') && r.method() === 'POST');
    await workspace.getByRole('button', { name: 'Send suggested fix', exact: true }).click();
    assert.deepEqual((await fix).postDataJSON().replace, ['Keep a checksum.']);
    await expect(workspace.getByRole('status')).toContainText('Suggested fix recorded');
  });
  await t.test('edit conflict retains draft, and narrow dark view remains readable', async () => {
    await workspace.getByRole('link', { name: 'Edit page', exact: true }).click();
    const editor = page.getByRole('textbox', { name: 'Markdown source, including optional frontmatter', exact: true });
    const draft = `${await editor.inputValue()}\nRetained conflict draft.\n`; await editor.fill(draft);
    await writeFile(server.documentPath, `${fixtureContent}\nConcurrent synthetic edit.\n`);
    await page.getByRole('button', { name: 'Save changes', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'A newer version exists' })).toBeVisible();
    await expect(workspace.locator('.dcol.inline')).toHaveCount(1);
    assert.equal(await editor.inputValue(), draft);
    await editor.fill(`${draft}\nConcurrent synthetic edit.\n`);
    await page.getByRole('button', { name: 'Save reviewed version', exact: true }).click();
    await expect(workspace.locator('.document-body')).toContainText('Retained conflict draft.');
    await workspace.getByRole('link', { name: 'Edit page', exact: true }).click();
    const recoveredDraft = `${await editor.inputValue()}\nDraft restored after leaving.\n`; await editor.fill(recoveredDraft);
    await hash('#/search');
    await page.getByRole('dialog').getByRole('button', { name: 'Leave and keep draft', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Library', exact: true })).toBeVisible();
    const current = await readFile(server.documentPath, 'utf8');
    await writeFile(server.documentPath, `${current}\nChanged while the draft was closed.\n`);
    await hash(`#/edit?ref=${encodeURIComponent(server.refs.document)}`);
    await expect(page.getByRole('heading', { name: 'A newer version exists' })).toBeVisible();
    assert.equal(await editor.inputValue(), recoveredDraft);
    await editor.fill(`${recoveredDraft}\nChanged while the draft was closed.\n`);
    await page.getByRole('button', { name: 'Save reviewed version', exact: true }).click();
    await expect(workspace.locator('.document-body')).toContainText('Draft restored after leaving.');
    await workspace.getByRole('link', { name: 'Edit page', exact: true }).click();
    const submitted = `${await editor.inputValue()}\nProtected submitted draft.\n`; await editor.fill(submitted);
    let release, started;
    const inFlight = new Promise(resolve => started = resolve);
    await page.route('**/api/asset/save', async route => { const response = await route.fetch(); started(); await new Promise(resolve => release = resolve); await route.fulfill({ response }); });
    await page.getByRole('button', { name: 'Save changes', exact: true }).click(); await inFlight;
    try {
      await expect(editor).toBeDisabled();
      await assert.rejects(editor.fill('Post-submit edit must not be accepted', { timeout: 200 }));
      assert.equal(await editor.inputValue(), submitted);
    } finally { release?.(); }
    await expect(workspace.locator('.document-body')).toContainText('Protected submitted draft.');
    await page.unroute('**/api/asset/save');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('combobox', { name: 'Appearance', exact: true }).selectOption('dark');
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
    await screenshot('parity-library-narrow-dark.png');
    const overflow = await page.evaluate(() => [...document.querySelectorAll('body *')].filter(el => el.getBoundingClientRect().right > innerWidth + 1).slice(0, 12).map(el => `${el.tagName}.${el.className}: ${Math.round(el.getBoundingClientRect().width)}px`));
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), JSON.stringify(overflow));
  });
  assert.deepEqual(failures, []);
});
