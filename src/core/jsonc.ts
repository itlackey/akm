/**
 * JSONC leaf: imports nothing, so `paths.ts` (which reads the config file's `paths`
 * key before the config module can load) and `common.ts` can both use it without
 * an import cycle.
 */

/**
 * Strip JavaScript-style comments from a JSON string (JSONC support).
 * Handles `//` line comments, which end at a line feed or a carriage return,
 * and `/* *​/` block comments while preserving comment-like sequences inside
 * quoted strings.
 */
export function stripJsonComments(text: string): string {
  let result = "";
  let i = 0;
  let inString = false;
  while (i < text.length) {
    if (inString) {
      if (text[i] === "\\") {
        result += text[i] + (text[i + 1] ?? "");
        i += 2;
        continue;
      }
      if (text[i] === '"') {
        inString = false;
      }
      result += text[i];
      i++;
      continue;
    }
    if (text[i] === '"') {
      inString = true;
      result += text[i];
      i++;
      continue;
    }
    if (text[i] === "/" && text[i + 1] === "/") {
      while (i < text.length && text[i] !== "\n" && text[i] !== "\r") i++;
      continue;
    }
    if (text[i] === "/" && text[i + 1] === "*") {
      i += 2;
      while (i < text.length && !(text[i] === "*" && text[i + 1] === "/")) i++;
      i += 2;
      continue;
    }
    result += text[i];
    i++;
  }
  return result;
}
