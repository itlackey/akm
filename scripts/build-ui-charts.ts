// Rebuild the checked-in, offline ECharts subset after updating its dependency or imports.
import { readFileSync } from "node:fs";

const license = ["echarts/LICENSE", "echarts/NOTICE", "zrender/LICENSE"]
  .map((file) => readFileSync(`node_modules/${file}`, "utf8"))
  .join("\n\n");
const result = await Bun.build({
  entrypoints: ["scripts/ui-echarts.ts"],
  target: "browser",
  format: "esm",
  minify: true,
  outdir: "src/assets/ui",
  naming: "echarts.js",
  banner: `/*! Generated by scripts/build-ui-charts.ts.\n${license.replaceAll("*/", "* /")}\n*/`,
});
if (!result.success) throw new Error(result.logs.map(String).join("\n"));
console.log(`Offline ECharts subset: ${result.outputs[0]?.size} bytes`);
